-- Adds posts.position — порядковый номер лекции внутри класса (1, 2, 3...).
-- Раньше "какая это лекция по счёту" определялось только порядком постов в
-- ленте (id DESC), из-за чего AI-репетитор класса не мог надёжно связать
-- "объясни 2 лекцию" с конкретным материалом. position проставляется
-- сервером при создании поста-лекции (см. crud/posts.py:_next_lecture_position)
-- и используется для сортировки и явной нумерации в контексте, отправляемом
-- модели (routers/ai.py).
--
-- NULL для не-лекционных постов и для лекций, созданных до этой миграции —
-- такие лекции просто попадают в конец списка при сортировке (см.
-- crud/posts.py:get_all_posts, ORDER BY position NULLS LAST).
ALTER TABLE posts ADD COLUMN IF NOT EXISTS position INTEGER;

-- Дата регистрации пользователя (users.created_at).
--
-- Колонки не было вовсе: админка показывала «Дата регистрации» из поля,
-- которого нет в модели, поэтому в таблице всегда стоял прочерк.
--
-- Намеренно БЕЗ DEFAULT и без бэкфилла: у существующих аккаунтов настоящей
-- даты регистрации взять неоткуда, а проставить им дату накатывания миграции
-- значило бы показать в интерфейсе заведомо ложную дату. Такие строки
-- остаются NULL, и карточка пользователя честно рисует «—».
--
-- Новые регистрации получают дату из приложения (models.User.created_at,
-- default=utcnow), поэтому DEFAULT в БД тоже не нужен.
ALTER TABLE users ADD COLUMN IF NOT EXISTS created_at TIMESTAMP;
